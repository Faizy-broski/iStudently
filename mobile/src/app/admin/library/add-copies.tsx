import { router, Stack, useLocalSearchParams } from 'expo-router';
import { BookOpen } from 'lucide-react-native';
import { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { View } from 'react-native';
import { useSWRConfig } from 'swr';

import { KeyboardAvoidingView, ScrollView } from '@/components/app/keyboard';
import { DateField } from '@/components/app/date-field';
import { LoadingList } from '@/components/app/states';
import { useToast } from '@/components/app/toast';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';
import { Icon } from '@/components/ui/icon';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Text } from '@/components/ui/text';
import { Textarea } from '@/components/ui/textarea';
import { isLibraryKey } from '@/features/admin/library';
import { adminLibrary } from '@/lib/api';
import { useApi } from '@/lib/data';

/** Add physical copies of a book; accession numbers are generated by the server (web: Add Copies dialog). */
export default function LibraryAddCopies() {
  const { t } = useTranslation();
  const toast = useToast();
  const { mutate } = useSWRConfig();
  const { id } = useLocalSearchParams<{ id: string }>();
  const book = useApi(id ? ['admin', 'library-book', id] : null, ([, , bid]) => adminLibrary.book(bid as string));
  const [count, setCount] = useState('1');
  const [purchaseDate, setPurchaseDate] = useState('');
  const [price, setPrice] = useState('');
  const [notes, setNotes] = useState('');
  const [saving, setSaving] = useState(false);

  async function save() {
    const n = parseInt(count, 10);
    if (!id || !n || n < 1 || n > 100) return toast.error(t('app.lb_copies_range'));
    setSaving(true);
    try {
      const r = await adminLibrary.addCopies(id, { numberOfCopies: n, purchase_date: purchaseDate || undefined, price: price ? parseFloat(price) : undefined, condition_notes: notes || undefined });
      if (!r.success) return toast.error(r.error || t('app.lb_copies_failed'));
      toast.success(t('app.lb_copies_added', { count: n }));
      await mutate(isLibraryKey);
      router.back();
    } finally {
      setSaving(false);
    }
  }

  if (book.isLoading) return <LoadingList />;
  const b = book.data;
  return (
    <KeyboardAvoidingView className="bg-background flex-1">
      <Stack.Screen options={{ title: t('app.lb_add_copies') }} />
      <ScrollView contentContainerClassName="gap-4 p-4 pb-10" keyboardShouldPersistTaps="handled">
        <Text className="text-muted-foreground text-sm">{t('app.lb_add_copies_desc')}</Text>
        {b ? (
          <Card>
            <CardContent className="gap-1 pt-4">
              <View className="flex-row items-center gap-2">
                <Icon as={BookOpen} className="text-primary size-4" />
                <Text className="font-semibold">{t('app.lb_book_details')}</Text>
              </View>
              <Text className="text-sm">{t('app.lb_title')}: {b.title}</Text>
              <Text className="text-sm">{t('app.lb_author')}: {b.author}</Text>
              <Text className="text-sm">{t('app.lb_current_copies', { total: b.total_copies, available: b.available_copies })}</Text>
            </CardContent>
          </Card>
        ) : null}
        <Card>
          <CardContent className="gap-4 pt-4">
            <View className="gap-1.5">
              <Label>{t('app.lb_number_of_copies')}</Label>
              <Input value={count} onChangeText={setCount} keyboardType="number-pad" maxLength={3} />
            </View>
            <DateField label={t('app.lb_purchase_date')} value={purchaseDate} onChange={setPurchaseDate} clearable />
            <View className="gap-1.5">
              <Label>{t('app.lb_price_per_copy')}</Label>
              <Input value={price} onChangeText={setPrice} keyboardType="decimal-pad" placeholder="0.00" />
            </View>
            <View className="gap-1.5">
              <Label>{t('app.lb_condition_notes')}</Label>
              <Textarea value={notes} onChangeText={setNotes} placeholder={t('app.lb_condition_notes_ph')} />
            </View>
            <View className="rounded-md bg-blue-50 p-3 dark:bg-blue-950/30">
              <Text className="text-sm text-blue-800 dark:text-blue-300">{t('app.lb_accession_note')}</Text>
            </View>
          </CardContent>
        </Card>
        <Button onPress={save} disabled={saving}>
          <Text>{saving ? t('app.lb_adding') : t('app.lb_add_copies')}</Text>
        </Button>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}
