// to Arabic-language printed editions of an-Nawawi's collection) but has NOT
// been checked word-for-word against an authoritative printed edition by a
// qualified reviewer. Check in particular: the matn of every hadith (longer
// ones especially — 2, 24, 29, and 36 are the longest and most error-prone to
// transcribe), the source citations (which scholars narrated/collected each
// hadith), and the narrator biographies (some death years are disputed among
// biographers; the dates here reflect commonly-cited figures, not a
// definitive ruling). See the plan's "Human review checkpoint" section.
