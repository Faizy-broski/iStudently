/**
 * Writes backend/migrations/jahbadh_grades_seed.sql from the single distribution source
 * (src/jahbadh/distribution.ts): the platform template (school_id NULL) of the 14 grades.
 *   npx tsx packages/shared-utils/scripts/jahbadh-seed-sql.ts
 * Ids are md5-derived so the seed is re-runnable (ON CONFLICT DO NOTHING).
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { JG_DISTRIBUTION, JG_DISTRIBUTION_VERSION } from '../src/jahbadh/distribution'

const q = (s: string | null) => (s === null ? 'NULL' : `'${s.replace(/'/g, "''")}'`)
const id = (...parts: (string | number)[]) => `md5(${q(['jg', JG_DISTRIBUTION_VERSION, ...parts].join('|'))})::uuid`

const lines: string[] = [
  '-- =============================================================',
  `-- Jahbadh grades: official distribution ${JG_DISTRIBUTION_VERSION} (platform template, school_id NULL)`,
  '-- =============================================================',
  '-- GENERATED by packages/shared-utils/scripts/jahbadh-seed-sql.ts from',
  '-- packages/shared-utils/src/jahbadh/distribution.ts — do not edit by hand.',
  '-- Run after jahbadh_grades.sql. Safe to re-run.',
  '',
  'BEGIN;',
  '',
]

for (const g of JG_DISTRIBUTION) {
  const ruleId = id(g.code)
  lines.push(`-- ${g.code}. ${g.name}`)
  lines.push(
    `INSERT INTO jg_grade_rules (id, school_id, version_label, grade_code, name, level, track, system_name, no_fail, total_min, exam_min, stage_names, rule_text, certificate_name, next_grade_name) VALUES (` +
      [
        ruleId, 'NULL', q(JG_DISTRIBUTION_VERSION), g.code, q(g.name), q(g.level), q(g.track), q(g.systemName),
        g.noFail, g.totalMin, g.examMin, `${q(JSON.stringify(g.stageNames))}::jsonb`, q(g.ruleText), q(g.certificateName), q(g.nextGradeName),
      ].join(', ') +
      ') ON CONFLICT (id) DO NOTHING;',
  )
  g.subjects.forEach((s, si) => {
    const subjectId = id(g.code, s.key)
    lines.push(
      `INSERT INTO jg_grade_subjects (id, rule_id, key, name, weekly_periods, display_order) VALUES (${subjectId}, ${ruleId}, ${q(s.key)}, ${q(s.name)}, ${s.weeklyPeriods}, ${si + 1}) ON CONFLICT (id) DO NOTHING;`,
    )
    const values: string[] = []
    s.stages.forEach((comps, stageIdx) =>
      comps.forEach((c, ci) =>
        values.push(`(${id(g.code, s.key, stageIdx + 1, ci + 1)}, ${subjectId}, ${stageIdx + 1}, ${ci + 1}, ${q(c.name)}, ${c.max}, ${!!c.exam})`),
      ),
    )
    lines.push(`INSERT INTO jg_components (id, subject_id, stage, sort_order, name, max_score, is_exam) VALUES\n  ${values.join(',\n  ')}\nON CONFLICT (id) DO NOTHING;`)
  })
  lines.push('')
}
lines.push('COMMIT;', '')

const out = resolve(__dirname, '../../../backend/migrations/jahbadh_grades_seed.sql')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}`)
