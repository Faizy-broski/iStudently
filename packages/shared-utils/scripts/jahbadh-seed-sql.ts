/**
 * Writes the seed of one memo year from the single distribution source (src/jahbadh/distribution*.ts):
 * the platform template (school_id NULL) of the 14 grades.
 *   npx tsx packages/shared-utils/scripts/jahbadh-seed-sql.ts [version]   (default: the current memo year)
 * 2024-2025 → backend/migrations/jahbadh_grades_seed.sql; other years → jahbadh_grades_seed_<year>.sql.
 * Ids are md5-derived so the seed is re-runnable (ON CONFLICT DO NOTHING). From 2026-2027 the seed also
 * writes the Wave 1 columns (monthly_kind, divisor, max_round2_subjects) and jg_subitems, so it must run
 * after jahbadh_wave1_2026_2027.sql. The 2024-2025 seed keeps its original format.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { JG_DISTRIBUTION_VERSION as CURRENT, JG_DISTRIBUTIONS } from '../src/jahbadh/distribution'

const JG_DISTRIBUTION_VERSION = process.argv[2] ?? CURRENT
const JG_DISTRIBUTION = JG_DISTRIBUTIONS[JG_DISTRIBUTION_VERSION]
if (!JG_DISTRIBUTION) throw new Error(`unknown memo year ${JG_DISTRIBUTION_VERSION}; known: ${Object.keys(JG_DISTRIBUTIONS).join(', ')}`)

const q = (s: string | null) => (s === null ? 'NULL' : `'${s.replace(/'/g, "''")}'`)
const id = (...parts: (string | number)[]) => `md5(${q(['jg', JG_DISTRIBUTION_VERSION, ...parts].join('|'))})::uuid`

const wave1 = JG_DISTRIBUTION_VERSION !== '2024-2025'

const lines: string[] = [
  '-- =============================================================',
  `-- Jahbadh grades: official distribution ${JG_DISTRIBUTION_VERSION} (platform template, school_id NULL)`,
  '-- =============================================================',
  '-- GENERATED by packages/shared-utils/scripts/jahbadh-seed-sql.ts from',
  '-- packages/shared-utils/src/jahbadh/distribution.ts — do not edit by hand.',
  wave1 ? '-- Run after jahbadh_grades.sql and jahbadh_wave1_2026_2027.sql. Safe to re-run.' : '-- Run after jahbadh_grades.sql. Safe to re-run.',
  '',
  'BEGIN;',
  '',
]

for (const g of JG_DISTRIBUTION) {
  const ruleId = id(g.code)
  lines.push(`-- ${g.code}. ${g.name}`)
  lines.push(
    `INSERT INTO jg_grade_rules (id, school_id, version_label, grade_code, name, level, track, system_name, no_fail, total_min, exam_min, stage_names, rule_text, certificate_name, next_grade_name${wave1 ? ', max_round2_subjects' : ''}) VALUES (` +
      [
        ruleId, 'NULL', q(JG_DISTRIBUTION_VERSION), g.code, q(g.name), q(g.level), q(g.track), q(g.systemName),
        g.noFail, g.totalMin, g.examMin, `${q(JSON.stringify(g.stageNames))}::jsonb`, q(g.ruleText), q(g.certificateName), q(g.nextGradeName),
        ...(wave1 ? [g.maxRound2Subjects ?? 0] : []),
      ].join(', ') +
      ') ON CONFLICT (id) DO NOTHING;',
  )
  g.subjects.forEach((s, si) => {
    const subjectId = id(g.code, s.key)
    lines.push(
      `INSERT INTO jg_grade_subjects (id, rule_id, key, name, weekly_periods, display_order) VALUES (${subjectId}, ${ruleId}, ${q(s.key)}, ${q(s.name)}, ${s.weeklyPeriods}, ${si + 1}) ON CONFLICT (id) DO NOTHING;`,
    )
    const values: string[] = []
    const subItems: string[] = []
    s.stages.forEach((comps, stageIdx) =>
      comps.forEach((c, ci) => {
        const compId = id(g.code, s.key, stageIdx + 1, ci + 1)
        values.push(
          wave1
            ? `(${compId}, ${subjectId}, ${stageIdx + 1}, ${ci + 1}, ${q(c.name)}, ${c.max}, ${!!c.exam}, ${q(c.monthly ?? null)}, ${c.divisor ?? 1})`
            : `(${compId}, ${subjectId}, ${stageIdx + 1}, ${ci + 1}, ${q(c.name)}, ${c.max}, ${!!c.exam})`,
        )
        c.subItems?.forEach((it, ii) =>
          subItems.push(`(${id(g.code, s.key, stageIdx + 1, ci + 1, 'si', ii + 1)}, ${subjectId}, ${compId}, ${ii + 1}, ${q(it.name)}, ${it.max})`),
        )
      }),
    )
    lines.push(
      wave1
        ? `INSERT INTO jg_components (id, subject_id, stage, sort_order, name, max_score, is_exam, monthly_kind, divisor) VALUES\n  ${values.join(',\n  ')}\nON CONFLICT (id) DO NOTHING;`
        : `INSERT INTO jg_components (id, subject_id, stage, sort_order, name, max_score, is_exam) VALUES\n  ${values.join(',\n  ')}\nON CONFLICT (id) DO NOTHING;`,
    )
    s.round2SubItems?.forEach((it, ii) => subItems.push(`(${id(g.code, s.key, 'r2', ii + 1)}, ${subjectId}, NULL, ${ii + 1}, ${q(it.name)}, ${it.max})`))
    if (wave1 && subItems.length) {
      lines.push(`INSERT INTO jg_subitems (id, subject_id, component_id, sort_order, name, max_score) VALUES\n  ${subItems.join(',\n  ')}\nON CONFLICT (id) DO NOTHING;`)
    }
  })
  lines.push('')
}
lines.push('COMMIT;', '')

const file = JG_DISTRIBUTION_VERSION === '2024-2025' ? 'jahbadh_grades_seed.sql' : `jahbadh_grades_seed_${JG_DISTRIBUTION_VERSION.replace('-', '_')}.sql`
const out = resolve(__dirname, '../../../backend/migrations', file)
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}`)
