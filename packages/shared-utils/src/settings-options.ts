export const DATE_FORMAT_OPTIONS = ['MMMM d yyyy', 'MMM d yy', 'd MMMM yyyy', 'd MMM yy', 'MM/dd/yyyy', 'dd/MM/yyyy', 'yyyy/MM/dd', 'dd.MM.yyyy', 'dd-MM-yyyy', 'yyyy-MM-dd'] as const
export const DEFAULT_DATE_FORMAT = 'MMMM d yyyy'

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']

/** Format with the date-fns tokens the web's date format setting uses (MMMM MMM MM d dd yyyy yy). English month names, as on the web. */
export function formatDatePattern(date: Date, pattern: string): string {
  const p = (n: number) => String(n).padStart(2, '0')
  return pattern.replace(/MMMM|MMM|MM|dd|d|yyyy|yy/g, (tok) => {
    switch (tok) {
      case 'MMMM': return MONTHS[date.getMonth()]
      case 'MMM': return MONTHS[date.getMonth()].slice(0, 3)
      case 'MM': return p(date.getMonth() + 1)
      case 'dd': return p(date.getDate())
      case 'd': return String(date.getDate())
      case 'yyyy': return String(date.getFullYear())
      default: return String(date.getFullYear()).slice(-2)
    }
  })
}
